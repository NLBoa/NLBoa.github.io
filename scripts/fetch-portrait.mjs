// The ASCII portrait on the About page comes from the GitHub profile card
// (github.com/NLBoa/NLBOA, assets/face_frames.json, made by tools/ascii_face.py).
// Usage: npm run assets:portrait
// Writes the front frame (small, used in the page's HTML and on the right
// monitor) and all frames (loaded only when the portrait starts to turn).
import { writeFileSync } from "node:fs";
import path from "node:path";

const SOURCE = "https://raw.githubusercontent.com/NLBoa/NLBOA/HEAD/assets/face_frames.json";
const root = path.resolve(import.meta.dirname, "..");

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`${response.status} ${SOURCE}`);
const data = await response.json();

// The "dark" set is the one drawn for a dark background.
const frames = data.dark.map((frame) => frame.map((line) => line.padEnd(data.cols).slice(0, data.cols)));
const meta = { cols: data.cols, rows: data.rows, cellRatio: data.cell_ratio, front: data.front, count: data.dark.length };

writeFileSync(path.join(root, "src/content/portrait-frames.json"), JSON.stringify({ ...meta, frames }) + "\n");
writeFileSync(
  path.join(root, "src/content/portrait-front.ts"),
  `// Generated by scripts/fetch-portrait.mjs from the GitHub profile card. Do not edit.
export const PORTRAIT = ${JSON.stringify(meta)} as const;

/** The portrait facing forward: ${data.rows} lines of ${data.cols} characters. */
export const portraitFront: string[] = ${JSON.stringify(frames[data.front], null, 2)};
`,
);
console.log(`${frames.length} frames, ${data.cols}x${data.rows}, front is frame ${data.front}`);
